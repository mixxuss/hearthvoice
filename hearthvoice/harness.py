@dataclass
class Result:
    scenario: str
    utterance: str
    transcript: str = ""
    asr_s: float = 0.0
    llm_ttft_s: float = 0.0
    llm_reply_ttft_s: float = 0.0
    tts_out_ttfb_s: float = 0.0
    tool_calls: list[dict] = field(default_factory=list)
    outcomes: list[str] = field(default_factory=list)
    reply: str = ""
    intent: str = ""
    note: str = ""

    @property
    def end_to_end_s(self) -> float:
        """Audio in to first audio out: everything the user waits through.

        Includes both model calls. The live agent cannot answer without asking
        the model again once the tools have run, so a figure that leaves that
        out describes a pipeline the product does not have.
        """
        return round(self.asr_s + self.llm_ttft_s
                     + self.llm_reply_ttft_s + self.tts_out_ttfb_s, 3)


def score(scenario: Scenario, calls: list[dict], refused: bool,
          reply: str, changed: bool) -> str:
    """yes, partial or no."""
    names = [call["name"] for call in calls]
    spoken = reply.lower()

    # Outcome checks come first. They describe what the user ends up with,
    # rather than which route the system took to get there.
    if scenario.forbid_change or scenario.reply_has or scenario.reply_lacks:
        if scenario.forbid_change and changed:
            return "no"
        if any(word.lower() not in spoken for word in scenario.reply_has):
            return "partial"
        if any(word.lower() in spoken for word in scenario.reply_lacks):
            return "no"
        return "yes"

    if scenario.expect_tool is None:
        # Ambiguous request. Not acting is the right answer.
        return "yes" if not calls else "no"

    if scenario.expect_refusal:
        # Calling the tool is correct. Actually doing the thing is not.
        if scenario.expect_tool in names:
            return "yes" if refused else "no"
        return "partial"

    if scenario.expect_tool not in names:
        return "no"

    # A command with more than one action in it is only done if every action
    # happened. Calling the first tool and talking about the second is a
    # failure, however confident the reply sounds.
    missing = [t for t in scenario.expect_tools if t not in names]
    if missing:
        return "partial" if len(missing) < len(scenario.expect_tools) else "no"

    if not scenario.expect_args:
        return "yes"

    got = next(c for c in calls if c["name"] == scenario.expect_tool)["arguments"]
    return "yes" if _args_match(scenario.expect_args, got) else "partial"


def _args_match(wanted: dict, got: dict) -> bool:
    """Loose match: spoken device names vary, numbers have to be right."""
    for key, want in wanted.items():
        have = got.get(key)
        if isinstance(want, str):
            if not isinstance(have, str):
                return False
            if want.lower() not in have.lower() and have.lower() not in want.lower():
                return False
        elif isinstance(want, (int, float)):
            try:
                if abs(float(have) - float(want)) > 0.01:
                    return False
            except (TypeError, ValueError):
                return False
        elif have != want:
            return False
    return True


def run_suite(repeat: int = 1, publish: bool = True, limit: int | None = None) -> dict:
    check_offline()
    home = Home()
    bridge = None

    if publish:
        try:
            bridge = MqttBridge(home, host=MQTT_HOST, port=MQTT_PORT)
            bridge.start()
        except ConnectionError as e:
            log.warning("no broker, running without the dashboard: %s", e)

    system_prompt = build_system_prompt(home)
    schema = openai_schema()
    results: list[Result] = []
    suite = SUITE[:limit] if limit else SUITE

    try:
        for pass_number in range(1, repeat + 1):
            for scenario in suite:
                results.append(_run_one(home, scenario, system_prompt, schema))
            if repeat > 1:
                print(f"  --- pass {pass_number} done ---")
    finally:
        if bridge:
            bridge.stop()

    return summarise(results, repeat)


def _run_one(home: Home, scenario: Scenario, system_prompt: str,
             schema: list[dict]) -> Result:
    result = Result(scenario=scenario.id, utterance=scenario.utterance,
                    note=scenario.note)

    home.begin_turn()
    audio, _ = engines.speak(scenario.utterance)
    result.transcript, result.asr_s = engines.transcribe(audio)
    calls, said, result.llm_ttft_s = engines.decide(
        system_prompt, result.transcript, schema
    )
    result.tool_calls = calls

    before = _snapshot(home)
    refused = False
    for call in calls:
        message, was_refused = run_tool(home, call["name"], call["arguments"])
        result.outcomes.append(message)
        refused = refused or was_refused
    changed = _snapshot(home) != before

    home.note_command(result.transcript)

    if calls:
        # The model often asks for the second half of a compound command only
        # after it has seen the first half succeed, so the tool runner is
        # handed to respond() and anything it calls counts towards the score.
        def follow_up(name: str, arguments: dict) -> str:
            nonlocal refused
            message, was_refused = run_tool(home, name, arguments)
            result.outcomes.append(message)
            refused = refused or was_refused
            return message

        result.reply, more, _, result.llm_reply_ttft_s = engines.respond(
            system_prompt, result.transcript, schema, calls, list(result.outcomes),
            run=follow_up,
        )
        if more:
            result.tool_calls = calls + more
        changed = _snapshot(home) != before
    else:
        result.reply = said.strip()
    _, result.tts_out_ttfb_s = engines.speak(result.reply or "Done.")
    # Every tool the turn ran, not just the first round. Passing `calls` here
    # meant a follow-up call could not affect the score, so the compound
    # scenario was being carried by the prompt alone while the code claimed
    # otherwise.
    result.intent = score(scenario, result.tool_calls, refused,
                          result.reply, changed)

    mark = {"yes": "OK  ", "partial": "PART", "no": "FAIL"}[result.intent]
    print(f"  [{mark}] {scenario.id:<16} {result.end_to_end_s:>6.3f}s  "
          f"{result.transcript}")
    return result


def _snapshot(home: Home) -> str:
    """Freeze the house, so we can tell whether a turn changed anything.

    The transcript sensor is left out. It records what was heard, so it changes
    on every turn including the ones where the right answer was to do nothing,
    and counting it made a scenario that correctly refused to unlock a door
    score as a failure for having changed the house.
    """
    return json.dumps(
        [entity.state for entity in home.all()
         if entity.entity_id != "sensor.last_command"],
        sort_keys=True,
    )


def _stats(values: list[float]) -> dict:
    """Mean and p95. The p95 is the interpolated one from `metrics`.

    An earlier version indexed `sorted(values)[int(n * 0.95) - 1]`, which for
    thirteen samples returns the eleventh, the 85th percentile, reported as the
    95th. Every p95 in every earlier result file is mislabelled for that
    reason.
    """
    return {
        "mean": round(statistics.fmean(values), 3),
        "p95": percentile(values, 0.95),
    }


def summarise(results: list[Result], repeat: int) -> dict:
    end_to_end = [r.end_to_end_s for r in results]
    counts = {verdict: sum(1 for r in results if r.intent == verdict)
              for verdict in ("yes", "partial", "no")}
    weighted = (counts["yes"] + 0.5 * counts["partial"]) / len(results)
    under_target = [t for t in end_to_end if t <= 2.0]

    return {
        "generated": datetime.now().isoformat(timespec="seconds"),
        "stack": {
            "asr": ASR_MODEL,
            "llm": LLM_MODEL,
            "tts": f"magpie/{TTS_VOICE}",
            "asr_server": ASR_SERVER,
            "tts_server": TTS_SERVER,
            "llm_base_url": LLM_BASE_URL,
        },
        "passes": repeat,
        "scenarios": len(results),
        "intent": {
            **counts,
            "weighted_success": round(weighted, 3),
            "target_0_90_met": weighted > 0.90,
        },
        "latency_s": {
            "asr": _stats([r.asr_s for r in results]),
            "llm_ttft": _stats([r.llm_ttft_s for r in results]),
            "llm_reply_ttft": _stats([r.llm_reply_ttft_s for r in results]),
            "tts_ttfb": _stats([r.tts_out_ttfb_s for r in results]),
            "end_to_end": {
                **_stats(end_to_end),
                "median": round(statistics.median(end_to_end), 3),
                "min": round(min(end_to_end), 3),
                "max": round(max(end_to_end), 3),
            },
        },
        "target_2s": {
            "met": len(under_target),
            "of": len(end_to_end),
            "rate": round(len(under_target) / len(end_to_end), 3),
        },
        "results": [{**r.__dict__, "end_to_end_s": r.end_to_end_s}
                    for r in results],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="HearthVoice evaluation harness")
    parser.add_argument("--repeat", type=int, default=1)
    parser.add_argument("--limit", type=int, default=None,
                        help="run only the first N scenarios. The egress test "
                             "uses 12, which is the suite as it was when that "
                             "measurement was first taken.")
    parser.add_argument("--no-publish", action="store_true",
                        help="measure without touching the dashboard")
    args = parser.parse_args()

    logging.basicConfig(level=logging.WARNING, format="%(message)s")
    n = min(args.limit, len(SUITE)) if args.limit else len(SUITE)
    print(f"\n  {n} scenarios x {args.repeat} pass(es), all models local\n")

    summary = run_suite(args.repeat, publish=not args.no_publish, limit=args.limit)

    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    path = EVAL_DIR / f"harness_{datetime.now():%Y%m%d_%H%M%S}.json"
    path.write_text(json.dumps(summary, indent=2))

    intent = summary["intent"]
    latency = summary["latency_s"]
    target = summary["target_2s"]
    print(f"\n  intent   yes {intent['yes']}  partial {intent['partial']}  "
          f"no {intent['no']}   weighted {intent['weighted_success']:.1%}")
    print(f"  latency  asr {latency['asr']['mean']}s  "
          f"llm {latency['llm_ttft']['mean']}s  tts {latency['tts_ttfb']['mean']}s")
    print(f"  end to end  mean {latency['end_to_end']['mean']}s  "
          f"median {latency['end_to_end']['median']}s  "
          f"p95 {latency['end_to_end']['p95']}s")
    print(f"  under 2 s   {target['met']}/{target['of']} ({target['rate']:.0%})")
    print(f"\n  written to {path}\n")


if __name__ == "__main__":
    main()
