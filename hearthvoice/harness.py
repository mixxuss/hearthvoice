@dataclass
class Scenario:
    """One thing said to the assistant, and what should come of it.

    Prefer the outcome checks to `expect_tool` wherever more than one route to
    the right answer is legitimate. An earlier version scored only which tool
    was called, and marked two correct behaviours as failures because the model
    got there a better way.
    """

    id: str
    utterance: str
    expect_tool: str | None = None
    expect_args: dict | None = None
    # Every tool the command requires. A sentence with two actions in it is
    # only carried out if both happen; checking the first alone let a scenario
    # that left the front door unlocked score as a success.
    #
    # This field goes after expect_args on purpose. The scenarios below pass
    # their arguments positionally, so inserting it earlier silently shifted
    # every expect_args dict into this field and failed five correct scenarios.
    expect_tools: tuple[str, ...] = ()
    expect_refusal: bool = False
    forbid_change: bool = False
    reply_has: tuple[str, ...] = ()
    reply_lacks: tuple[str, ...] = ()
    note: str = ""


