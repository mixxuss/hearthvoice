"""Reproducible evaluation of the offline stack.

Runs a fixed set of spoken commands through the same three Spark models and the
same tool layer the live agent uses, without needing anyone at a microphone.
Each run writes a JSON file, so the numbers in the report can be regenerated by
anyone with the stack running.

One scenario goes: Magpie says the sentence, Parakeet hears it back, qwen3.5
decides which tools to call, the tools run against the real house, and Magpie
speaks the reply.

What this does not measure, and the report says so, is microphone capture and
voice-activity endpointing. Those add time a headless run cannot see, so the
figures here are a floor rather than a conversational measurement.

    python -m hearthvoice.harness
    python -m hearthvoice.harness --repeat 3
"""

